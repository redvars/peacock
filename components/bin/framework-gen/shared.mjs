// Pieces every framework package gets: the registration layer (one module per tag that defines
// the element and the tags it renders) and helpers the emitters share.

export const HEADER = '// Generated by components/bin/framework-gen.mjs from custom-elements.json. Do not edit.\n';

/** The import of an element's class type from the package's published declarations. */
export function classTypeImport(element, packageName, alias) {
  const from = `${packageName}/${element.typesPath}`;
  return element.exportName === 'default'
    ? `import type ${alias} from '${from}';`
    : `import type { ${element.className} as ${alias} } from '${from}';`;
}

/**
 * Type imports for an event's detail, aliased so they cannot clash with the generated names, and
 * the event type rewritten to use the aliases.
 */
export function eventTypeWithImports(event) {
  let type = event.type;
  const imports = [];
  for (const { name, from } of event.imports) {
    const alias = `T_${name}`;
    type = type.replace(new RegExp(`\\b${name}\\b`, 'g'), alias);
    imports.push({ line: `import type { ${name} as ${alias} } from '${from}';`, key: `${from}#${name}` });
  }
  return { type, imports };
}

/** Collects import lines once each, in first-seen order. */
export class ImportSet {
  #lines = new Map();

  add(line, key = line) {
    if (!this.#lines.has(key)) this.#lines.set(key, line);
  }

  toString() {
    return [...this.#lines.values()].join('\n');
  }
}

export function isIdentifier(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name);
}

/** JSDoc block from a description, or nothing. */
export function jsdoc(text, indent = '') {
  const clean = (text || '').trim().replace(/\*\//g, '*\\/');
  if (!clean) return '';
  const lines = clean.split(/\r?\n/);
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map(l => `${indent} * ${l}`.trimEnd()).join('\n')}\n${indent} */\n`;
}

/**
 * The registration layer, written into every framework package as `generated/define/`.
 *
 * Peacock's loader finds component files from its own URL, which bundlers rewrite, so the
 * bindings define elements themselves: importing `define/wc-select.js` defines `wc-select` and
 * every Peacock tag it renders, such as `wc-option` and `wc-icon`.
 */
export function emitDefineLayer(model, packageName) {
  const files = {};
  const entries = [];

  files['define-element.ts'] = `${HEADER}
const warned = new Set<string>();

/**
 * Defines \`tagName\` once. When other code (a second copy or another version of Peacock) already
 * defined it, the existing definition stays and this warns once.
 */
export function defineElement(tagName: string, elementClass: CustomElementConstructor): void {
  if (typeof customElements === 'undefined') return;
  const existing = customElements.get(tagName);
  if (!existing) {
    customElements.define(tagName, elementClass);
  } else if (existing !== elementClass && !warned.has(tagName)) {
    warned.add(tagName);
    // eslint-disable-next-line no-console
    console.warn(
      \`[peacock] <\${tagName}> is already defined by other code, so Peacock's version was not registered. Load one copy of Peacock per page.\`,
    );
  }
}
`;

  for (const element of model.elements) {
    const entry = `${packageName}/${element.entry}`;
    const types = `${packageName}/${element.typesPath}`;
    entries.push(
      `declare module '${entry}' {\n  export { ${
        element.exportName === 'default' ? 'default' : element.className
      } } from '${types}';\n}`,
    );

    const runtimeImport =
      element.exportName === 'default'
        ? `import ElementClass from '${entry}';`
        : `import { ${element.className} as ElementClass } from '${entry}';`;
    const deps = element.dependencies.map(tag => `import './${tag}.js';`).join('\n');

    files[`define/${element.tagName}.ts`] = `${HEADER}/// <reference path="../entries.d.ts" />
${runtimeImport}
${classTypeImport(element, packageName, 'ElementType')}
import { defineElement } from '../define-element.js';
${deps ? `${deps}\n` : ''}
defineElement('${element.tagName}', ElementClass);

/** The \`<${element.tagName}>\` class, defined as a side effect of importing this module. */
const definedClass: typeof ElementType = ElementClass;
export default definedClass;
`;
  }

  // Build-time only: types for the per-component entry files, which ship without declarations
  // of their own. Emitted declarations never reference these modules.
  files['entries.d.ts'] = `${HEADER}\n${entries.join('\n\n')}\n`;
  return files;
}
